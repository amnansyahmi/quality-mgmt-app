// Add or rename icons in the map below, then run: npm run build:icons
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.dirname(path.dirname(fileURLToPath(import.meta.url)));
const iconDir = path.join(root, "node_modules", "lucide-static", "icons");
const version = JSON.parse(fs.readFileSync(path.join(root, "node_modules", "lucide-static", "package.json"), "utf8")).version;

// Semantic name used in views -> Lucide icon name.
